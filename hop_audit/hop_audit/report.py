"""Writers: per-question JSONL, per-hop and per-agent CSVs, summary JSON and a Markdown report."""
from __future__ import annotations

import csv
import json
from collections import Counter
from pathlib import Path
from typing import Dict, List

from .gold import GoldQuestion
from .scoring import LABEL_ORDER


def _short(s: str, n: int = 60) -> str:
    s = " ".join(str(s).split())
    return s if len(s) <= n else s[: n - 1] + "…"


def write_pipeline(out_dir: Path, rows: List[dict], summary: dict) -> None:
    out_dir.mkdir(parents=True, exist_ok=True)
    with open(out_dir / "per_question.jsonl", "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    with open(out_dir / "per_question.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["qid", "type", "label", "em", "f1", "final_abstain", "prediction", "gold",
                    "n_latent_hops", "hop_statuses", "agents_committed_gold", "agents_mentioning_gold"])
        for r in rows:
            w.writerow([r["qid"], r["type"], r["label"], r["em"], r["f1"], r["final_abstain"], r["prediction"],
                        " | ".join(r["gold"]), r["n_latent_hops"], ";".join(r["hop_statuses"]),
                        ";".join(a for a, v in r["agent_answer_hit"].items() if v),
                        ";".join(a for a, v in r["agent_text_mentions_gold"].items() if v)])
    with open(out_dir / "per_hop.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(["qid", "hop_index", "items", "modalities", "in_context", "status", "first_stage_surfaced",
                    "surfaced_by", "raw_available_to", "final_text_mentions", "channels"])
        for r in rows:
            for h in r["hops"]:
                w.writerow([r["qid"], h["hop_index"], " | ".join(h["items"]), ";".join(h["modalities"]),
                            h["in_context"], h["status"], h["first_stage_surfaced"],
                            ";".join(a for a, v in h["surfaced_by_agent"].items() if v),
                            ";".join(a for a, v in h["raw_available"].items() if v),
                            h["final_text_mentions"],
                            ";".join(f"{c['from']}->{c['to']}:{c['outcome']}" for c in h["channels"])])
    with open(out_dir / "summary.json", "w", encoding="utf-8") as f:
        json.dump(summary, f, indent=2, ensure_ascii=False)


def gold_stats(gold: Dict[str, GoldQuestion]) -> dict:
    qs = list(gold.values())
    hops = [h for q in qs for h in q.hops]
    latent = [h for h in hops if h.latent]
    return {
        "questions": len(qs),
        "with_intermediate_answers": sum(1 for q in qs if q.hops),
        "compositional": sum(1 for q in qs if q.compositional),
        "hops": len(hops), "latent_hops": len(latent), "given_hops": len(hops) - len(latent),
        "latent_hop_modalities": dict(Counter(m for h in latent for m in h.modalities)),
        "questions_with_latent_hop": sum(1 for q in qs if q.latent_hops),
        "answer_named_in_question": sum(1 for q in qs if q.answer_in_question),
    }


def write_report(path: Path, results: Dict[str, dict], dev_stats: dict, notes: Dict[str, str]) -> None:
    L = ["# Hop-level audit report", "",
         "Generated by `run_hop_audit.py`. Small-sample runs are for checking the code and spotting patterns, "
         "not for claims: with 16 questions, one question is 6 percentage points.", ""]
    if dev_stats:
        L += ["## Gold hop structure, MMQA dev", "",
              "| quantity | value |", "|---|---|"]
        L += [f"| {k.replace('_', ' ')} | {v} |" for k, v in dev_stats.items()]
        L += [""]
    L += ["## Pipelines at a glance", "",
          "| pipeline | n | EM | F1 | abstain | latent hops | recall S1 | recall S2 | recall last | hand-off loss (stage) | hand-off loss (strict) |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for name, res in results.items():
        s = res["summary"]
        rec = s["bridge_recall_by_stage"]
        stage_keys = [k for k in rec if k.startswith("S")]
        last = rec.get(stage_keys[-1]) if stage_keys else None
        hl, hs = s["handoff_loss_stage_level"], s["handoff_loss_strict_channel"]
        L.append(f"| {name} | {s['n_questions']} | {s['EM']} | {s['mean_F1']} | {s['final_abstain_rate']} | "
                 f"{s['latent_hops_in_context']} | {rec.get('S1')} | {rec.get('S2')} | {last} | "
                 f"{hl['lost_by_last_stage']}/{hl['surfaced_at_first_stage']} | "
                 f"{hs['dropped']}/{hs['carried'] + hs['dropped']} |")
    L += ["", "## Failure attribution (one label per question)", "",
          "| pipeline | " + " | ".join(LABEL_ORDER) + " |", "|---|" + "---|" * len(LABEL_ORDER)]
    for name, res in results.items():
        lab = res["summary"]["labels"]
        L.append(f"| {name} | " + " | ".join(str(lab[k]) for k in LABEL_ORDER) + " |")
    for name, res in results.items():
        L += ["", f"## {name}", ""]
        if notes.get(name):
            L += [notes[name], ""]
        s = res["summary"]
        if s["agent_recall_when_raw_available"]:
            L += ["Agent recall of latent hops whose evidence it saw raw:", "",
                  "| agent | available | surfaced | recall |", "|---|---|---|---|"]
            L += [f"| {a} | {v['available']} | {v['surfaced']} | {v['recall']} |"
                  for a, v in s["agent_recall_when_raw_available"].items()]
            L += [""]
        if s["handoff_loss_strict_channel"]["by_channel"]:
            L += ["Strict hand-off channels (downstream agent can reach the hop only through upstream):", "",
                  "| channel | outcomes |", "|---|---|"]
            L += [f"| {k} | {v} |" for k, v in s["handoff_loss_strict_channel"]["by_channel"].items()]
            L += [""]
        L += ["| qid | type | label | prediction | gold | hops |", "|---|---|---|---|---|---|"]
        for r in res["rows"]:
            L.append(f"| {r['qid'][:8]} | {r['type']} | **{r['label']}** | {_short(r['prediction'], 40)} | "
                     f"{_short(' | '.join(r['gold']), 40)} | {', '.join(r['hop_statuses']) or '-'} |")
    path.write_text("\n".join(L) + "\n", encoding="utf-8")
